    // REPORT 2: SHAREPOINT & EXTERNAL ACCESS
    // ═══════════════════════════════════════════════════════════════

    public async Task<string> GenerateSharePointReportAsync()
    {
        _logger.LogInformation("Generating SharePoint & External Access Report");

        var now = GetAtlanticTime();
        var periodStart = now.AddDays(-14);
        var startDate = periodStart.ToUniversalTime().ToString("yyyy-MM-ddTHH:mm:ssZ");
        var endDate = now.ToUniversalTime().ToString("yyyy-MM-ddTHH:mm:ssZ");

        // Gather data
        var guestTask = _graph.GetGuestUsersAsync();
        var sharingParams = new Dictionary<string, string>
        {
            ["start_date"] = startDate,
            ["end_date"] = endDate
        };
        var sharingTask = _hunting.RunTemplateQueryAsync("search_external_sharing", sharingParams);

        await Task.WhenAll(guestTask, sharingTask);

        var guestJson = await guestTask;
        var sharingJson = await sharingTask;

        var guests = ParseGuestUsers(guestJson);
        var sharingEvents = ParseSharingEvents(sharingJson);

        var periodString = $"{periodStart:MMMM d} – {now:MMMM d, yyyy}";
        var timeZone = IsAtlanticDaylightTime(now) ? "ADT" : "AST";

        // Count anonymous links
        int anonymousLinks = sharingEvents.Count(e =>
            e.ActionType.Contains("Anonymous", StringComparison.OrdinalIgnoreCase));
        int pendingGuests = guests.Count(g =>
            g.ExternalUserState?.Equals("PendingAcceptance", StringComparison.OrdinalIgnoreCase) == true
            || string.IsNullOrEmpty(g.ExternalUserState));

        // Expiring access — guests inactive 60+ days or still pending
        var expiringGuests = guests.Where(g =>
            g.ExternalUserState?.Equals("PendingAcceptance", StringComparison.OrdinalIgnoreCase) == true
            || string.IsNullOrEmpty(g.ExternalUserState)
            || (g.LastSignIn.HasValue && (now.ToUniversalTime() - g.LastSignIn.Value).TotalDays > 60)
            || (!g.LastSignIn.HasValue && g.CreatedDate.HasValue && (now.ToUniversalTime() - g.CreatedDate.Value).TotalDays > 60)
        ).ToList();

        var sb = new StringBuilder();
        sb.Append(GetHtmlHead("SFI SharePoint & External Access Report"));
        sb.Append(GetHeader("SharePoint & External Access Report",
            "Biweekly external access review — generated by SFI Security Agent", periodString));

        // Stats bar
        sb.Append("<div class=\"stats-bar\">");
        sb.Append($"<div class=\"stat-item\"><div class=\"stat-number blue\">{guests.Count}</div><div class=\"stat-label\">Guest Users</div></div>");
        sb.Append($"<div class=\"stat-item\"><div class=\"stat-number orange\">{sharingEvents.Count}</div><div class=\"stat-label\">External Shares</div></div>");
        sb.Append($"<div class=\"stat-item\"><div class=\"stat-number red\">{anonymousLinks}</div><div class=\"stat-label\">Anonymous Links</div></div>");
        sb.Append($"<div class=\"stat-item\"><div class=\"stat-number orange\">{expiringGuests.Count}</div><div class=\"stat-label\">Expiring Access</div></div>");
        sb.Append("</div>");

        // External Sharing Section
        sb.Append("<div class=\"section\">");
        sb.Append("<div class=\"section-header\"><div class=\"section-icon yellow\">🔗</div><div class=\"section-title\">External Sharing Activity</div></div>");
        sb.Append($"<div class=\"section-summary\">{sharingEvents.Count} external sharing events in the past 2 weeks.</div>");

        if (anonymousLinks > 0)
        {
            sb.Append($"<div class=\"alert-box\">⚠️ <strong>{anonymousLinks} anonymous link{(anonymousLinks > 1 ? "s" : "")}</strong> created. Anonymous links allow anyone with the link to access the file without authentication.</div>");
        }

        sb.Append("<table><thead><tr><th>Date (" + timeZone + ")</th><th>Shared By</th><th>File / Folder</th><th>Shared With</th><th>Site</th><th>Type</th></tr></thead><tbody>");
        foreach (var e in sharingEvents.Take(100))
        {
            var date = ConvertToAtlantic(e.Timestamp);
            var badgeClass = e.ActionType.Contains("Anonymous", StringComparison.OrdinalIgnoreCase) ? "badge-high" : "badge-info";
            var typeLabel = e.ActionType.Contains("Anonymous", StringComparison.OrdinalIgnoreCase) ? "Anonymous Link" : "Specific People";
            sb.Append($"<tr><td>{date}</td><td>{Esc(e.User)}</td><td>{Esc(TruncateFileName(e.ItemName))}</td>");
            sb.Append($"<td>{Esc(e.SharedWith)}</td><td>{Esc(ShortenSiteUrl(e.SiteUrl))}</td>");
            sb.Append($"<td><span class=\"badge {badgeClass}\">{typeLabel}</span></td></tr>");
        }
        sb.Append("</tbody></table></div>");

        // Guest Users Section
        sb.Append("<div class=\"section\">");
        sb.Append("<div class=\"section-header\"><div class=\"section-icon blue\">👤</div><div class=\"section-title\">Guest Users</div></div>");
        sb.Append($"<div class=\"section-summary\">{guests.Count} guest users in the tenant. {pendingGuests} have not accepted their invitation.</div>");
        sb.Append("<table><thead><tr><th>Name</th><th>Email</th><th>Company</th><th>Status</th><th>Created</th><th>Last Active</th></tr></thead><tbody>");
        foreach (var g in guests)
        {
            var statusBadge = g.ExternalUserState?.Equals("Accepted", StringComparison.OrdinalIgnoreCase) == true
                ? "<span class=\"badge badge-compliant\">Accepted</span>"
                : "<span class=\"badge badge-noncompliant\">Pending</span>";
            var created = g.CreatedDate?.ToString("yyyy-MM-dd") ?? "—";
            var lastActive = g.LastSignIn.HasValue ? g.LastSignIn.Value.ToString("yyyy-MM-dd") : "Never";

            sb.Append($"<tr><td>{Esc(g.DisplayName)}</td><td>{Esc(g.Email)}</td><td>{Esc(g.Company)}</td>");
            sb.Append($"<td>{statusBadge}</td><td>{created}</td><td>{lastActive}</td></tr>");
        }
        sb.Append("</tbody></table></div>");

        // Expiring Guest Access Section
        sb.Append("<div class=\"section\">");
        sb.Append("<div class=\"section-header\"><div class=\"section-icon red\">⏰</div><div class=\"section-title\">Expiring Guest Access</div></div>");
        sb.Append("<div class=\"section-summary\">Guest users inactive for 60+ days or with pending invitations.</div>");

        if (expiringGuests.Any(g => g.ExternalUserState?.Equals("PendingAcceptance", StringComparison.OrdinalIgnoreCase) == true || string.IsNullOrEmpty(g.ExternalUserState)))
        {
            var pendingCount = expiringGuests.Count(g => g.ExternalUserState?.Equals("PendingAcceptance", StringComparison.OrdinalIgnoreCase) == true || string.IsNullOrEmpty(g.ExternalUserState));
            sb.Append($"<div class=\"alert-box red\">🔴 <strong>{pendingCount} guest account{(pendingCount > 1 ? "s" : "")}</strong> have pending invitations that may need to be resent or removed.</div>");
        }

        sb.Append("<table><thead><tr><th>Name</th><th>Email</th><th>Created</th><th>Last Active</th><th>Days Since Activity</th><th>Recommendation</th></tr></thead><tbody>");
        foreach (var g in expiringGuests)
        {
            var created = g.CreatedDate?.ToString("yyyy-MM-dd") ?? "—";
            var lastActive = g.LastSignIn.HasValue ? g.LastSignIn.Value.ToString("yyyy-MM-dd") : "Never";
            int daysSince;
            string recommendation;
            string badgeClass;

            if (!g.LastSignIn.HasValue)
            {
                daysSince = g.CreatedDate.HasValue ? (int)(now.ToUniversalTime() - g.CreatedDate.Value).TotalDays : 0;
                recommendation = "Resend or Remove";
                badgeClass = "badge-high";
            }
            else
            {
                daysSince = (int)(now.ToUniversalTime() - g.LastSignIn.Value).TotalDays;
                recommendation = daysSince > 90 ? "Review & Remove" : "Monitor";
                badgeClass = daysSince > 90 ? "badge-high" : "badge-medium";
            }

            var daysColor = daysSince > 90 ? "var(--sfi-red)" : "var(--sfi-orange)";
            var daysLabel = !g.LastSignIn.HasValue ? $"{daysSince} (pending)" : daysSince.ToString();

            sb.Append($"<tr><td>{Esc(g.DisplayName)}</td><td>{Esc(g.Email)}</td><td>{created}</td><td>{lastActive}</td>");
            sb.Append($"<td style=\"font-weight:700;color:{daysColor}\">{daysLabel}</td>");
            sb.Append($"<td><span class=\"badge {badgeClass}\">{recommendation}</span></td></tr>");
        }
        sb.Append("</tbody></table></div>");

        // Footer
        sb.Append(GetFooter("SharePoint & External Access Report", now, timeZone));
        sb.Append("</body></html>");

        _logger.LogInformation("SharePoint & External Access Report generated successfully");
        return sb.ToString();
    }

