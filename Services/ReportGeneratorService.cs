    private record VulnInfo(string DeviceName, List<string> CveIds, double MaxCvss, int TotalVulns, List<string> Software);

    private List<VulnInfo> ParseVulnerabilities(string json)
    {
        var vulns = new List<VulnInfo>();
        try
        {
            using var doc = JsonDocument.Parse(json);
            if (doc.RootElement.TryGetProperty("results", out var results))
            {
                foreach (var item in results.EnumerateArray())
                {
                    var cves = new List<string>();
                    var software = new List<string>();
                    if (item.TryGetProperty("CVEs", out var cveProp))
                    {
                        if (cveProp.ValueKind == JsonValueKind.Array)
                            cves = cveProp.EnumerateArray().Select(c => c.GetString() ?? "").ToList();
                        else if (cveProp.ValueKind == JsonValueKind.String)
                            cves = JsonSerializer.Deserialize<List<string>>(cveProp.GetString()!) ?? new();
                    }
                    if (item.TryGetProperty("Software", out var swProp))
                    {
                        if (swProp.ValueKind == JsonValueKind.Array)
                            software = swProp.EnumerateArray().Select(s => s.GetString() ?? "").ToList();
                        else if (swProp.ValueKind == JsonValueKind.String)
                            software = JsonSerializer.Deserialize<List<string>>(swProp.GetString()!) ?? new();
                    }

                    vulns.Add(new VulnInfo(
                        DeviceName: item.TryGetProperty("DeviceName", out var dn) ? dn.GetString() ?? "" : "",
                        CveIds: cves,
                        MaxCvss: item.TryGetProperty("MaxCVSS", out var mc) ? mc.GetDouble() : 0,
                        TotalVulns: item.TryGetProperty("TotalVulns", out var tv) ? tv.GetInt32() : 0,
                        Software: software
                    ));
                }
            }
        }
        catch (Exception ex)
        {
            _logger.LogWarning(ex, "Failed to parse vulnerabilities");
        }
        return vulns;
    }

