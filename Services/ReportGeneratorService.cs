    private static string Esc(string? value) =>
        System.Net.WebUtility.HtmlEncode(value ?? "—");

    private static string ConvertToAtlantic(DateTime? utcDate)
    {
        if (!utcDate.HasValue) return "—";
        var atlantic = GetAtlanticTime(utcDate.Value);
        var tz = IsAtlanticDaylightTime(atlantic) ? "ADT" : "AST";
        return $"{atlantic:yyyy-MM-dd HH:mm}";
    }

    private static DateTime GetAtlanticTime(DateTime? utcDate = null)
    {
        var utc = utcDate ?? DateTime.UtcNow;
        try
        {
            var tz = TimeZoneInfo.FindSystemTimeZoneById("America/Halifax");
            return TimeZoneInfo.ConvertTimeFromUtc(utc.Kind == DateTimeKind.Utc ? utc : DateTime.SpecifyKind(utc, DateTimeKind.Utc), tz);
        }
        catch
        {
            // Fallback: manually calculate AST/ADT
            var offset = IsAtlanticDaylightTime(utc) ? -3 : -4;
            return utc.AddHours(offset);
        }
    }

    private static bool IsAtlanticDaylightTime(DateTime date)
    {
        try
        {
            var tz = TimeZoneInfo.FindSystemTimeZoneById("America/Halifax");
            return tz.IsDaylightSavingTime(date);
        }
        catch
        {
            // Second Sunday of March to first Sunday of November
            var year = date.Year;
            var dstStart = GetNthDayOfWeek(year, 3, DayOfWeek.Sunday, 2).AddHours(2);
            var dstEnd = GetNthDayOfWeek(year, 11, DayOfWeek.Sunday, 1).AddHours(2);
            return date >= dstStart && date < dstEnd;
        }
    }

    private static DateTime GetNthDayOfWeek(int year, int month, DayOfWeek dow, int n)
    {
        var first = new DateTime(year, month, 1);
        var offset = ((int)dow - (int)first.DayOfWeek + 7) % 7;
        return first.AddDays(offset + 7 * (n - 1));
    }

    private static string TruncateFileName(string path)
    {
        if (string.IsNullOrEmpty(path)) return "—";
        var name = path.Contains('/') ? path.Split('/').Last() : path;
        return name.Length > 50 ? name[..47] + "..." : name;
    }

    private static string ShortenSiteUrl(string url)
    {
        if (string.IsNullOrEmpty(url)) return "—";
        // Extract /sites/Name from full URL
        var idx = url.IndexOf("/sites/", StringComparison.OrdinalIgnoreCase);
        if (idx >= 0)
        {
            var rest = url[(idx)..];
            var parts = rest.Split('/', StringSplitOptions.RemoveEmptyEntries);
            return parts.Length >= 2 ? $"/{parts[0]}/{parts[1]}" : rest;
        }
        return url.Length > 40 ? url[..37] + "..." : url;
    }
