    private record ComplianceSummary(int Compliant, int Noncompliant, int Unknown);

    private ComplianceSummary ParseComplianceSummary(string json)
    {
        int compliant = 0, noncompliant = 0, unknown = 0;
        try
        {
            using var doc = JsonDocument.Parse(json);
            var root = doc.RootElement;

            // The compliance summary returns a flat object with totalDevices, compliant, noncompliant, etc.
            if (root.TryGetProperty("compliant", out var c))
                compliant = c.GetInt32();
            if (root.TryGetProperty("noncompliant", out var nc))
                noncompliant = nc.GetInt32();
            if (root.TryGetProperty("unknown", out var unk))
                unknown = unk.GetInt32();
            if (root.TryGetProperty("inGracePeriod", out var igp))
                unknown += igp.GetInt32();
            if (root.TryGetProperty("configManager", out var cm))
                unknown += cm.GetInt32();
        }
        catch (Exception ex)
        {
            _logger.LogWarning(ex, "Failed to parse compliance summary");
        }
        return new ComplianceSummary(compliant, noncompliant, unknown);
    }

