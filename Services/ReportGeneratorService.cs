using Microsoft.Extensions.Logging;
using SecurityAgent.Config;
using System.Text;
using System.Text.Json;

namespace SecurityAgent.Services;

public class ReportGeneratorService
{
    private readonly IntuneService _intune;
    private readonly GraphApiService _graph;
    private readonly DefenderApiService _defender;
    private readonly AdvancedHuntingService _hunting;
    private readonly AgentConfiguration _config;
    private readonly ILogger<ReportGeneratorService> _logger;

    public ReportGeneratorService(
        IntuneService intune,
        GraphApiService graph,
        DefenderApiService defender,
        AdvancedHuntingService hunting,
        AgentConfiguration config,
        ILogger<ReportGeneratorService> logger)
    {
        _intune = intune;
        _graph = graph;
        _defender = defender;
        _hunting = hunting;
        _config = config;
        _logger = logger;
    }

