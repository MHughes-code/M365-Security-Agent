    // REPORT 1: DEVICES & VULNERABILITIES
    // ═══════════════════════════════════════════════════════════════

    public async Task<string> GenerateDevicesReportAsync()
    {
        _logger.LogInformation("Generating Devices & Vulnerabilities Report");

        // Gather all data in parallel where possible
        var complianceTask = _intune.GetDeviceComplianceSummaryAsync();
        var noncompliantTask = _intune.GetNoncompliantDevicesAsync();
        var updateRingsTask = _intune.GetWindowsUpdateRingsAsync();
        var updateStatusTask = _intune.GetWindowsUpdateStatusAsync();
        var staleTask = _intune.GetStaleDevicesAsync(30);

        // Vulnerabilities via Advanced Hunting — per-device breakdown + overall summary
        var vulnParams = new Dictionary<string, string>
        {
            ["severity_filter"] = "\"Critical\", \"High\""
        };
        var vulnTask = _hunting.RunTemplateQueryAsync("search_device_vulnerabilities", vulnParams);
        var vulnSummaryTask = _hunting.RunTemplateQueryAsync("search_vulnerability_summary", new Dictionary<string, string>());

        await Task.WhenAll(complianceTask, noncompliantTask, updateRingsTask, updateStatusTask, staleTask, vulnTask, vulnSummaryTask);

        var complianceJson = await complianceTask;
        var noncompliantJson = await noncompliantTask;
        var updateRingsJson = await updateRingsTask;
        var updateStatusJson = await updateStatusTask;
        var staleJson = await staleTask;
        var vulnJson = await vulnTask;
        var vulnSummaryJson = await vulnSummaryTask;

        // Parse the data
        var compliance = ParseComplianceSummary(complianceJson);
        var noncompliantDevices = ParseNoncompliantDevices(noncompliantJson);
        var updateRings = ParseUpdateRings(updateRingsJson);
        var updateStatus = ParseUpdateStatus(updateStatusJson);
        var staleDevices = ParseStaleDevices(staleJson);
        var vulnerabilities = ParseVulnerabilities(vulnJson);
        var vulnSummary = ParseVulnSummary(vulnSummaryJson);

        // Get report period
        var now = GetAtlanticTime();
        var periodEnd = now;
        var periodStart = now.AddDays(-14);
        var periodString = $"{periodStart:MMMM d} – {periodEnd:MMMM d, yyyy}";
        var timeZone = IsAtlanticDaylightTime(now) ? "ADT" : "AST";

        var sb = new StringBuilder();
        sb.Append(GetHtmlHead("SFI Devices & Vulnerabilities Report"));
        sb.Append(GetHeader("Devices & Vulnerabilities Report",
            "Biweekly security posture summary — generated by SFI Security Agent", periodString));

        // Stats bar
        sb.Append("<div class=\"stats-bar\">");
        sb.Append($"<div class=\"stat-item\"><div class=\"stat-number green\">{compliance.Compliant}</div><div class=\"stat-label\">Compliant</div></div>");
        sb.Append($"<div class=\"stat-item\"><div class=\"stat-number red\">{compliance.Noncompliant}</div><div class=\"stat-label\">Noncompliant</div></div>");
        sb.Append($"<div class=\"stat-item\"><div class=\"stat-number orange\">{vulnSummary.Total}</div><div class=\"stat-label\">Vulnerabilities</div></div>");
        sb.Append($"<div class=\"stat-item\"><div class=\"stat-number blue\">{staleDevices.Count}</div><div class=\"stat-label\">Stale Devices</div></div>");
        sb.Append("</div>");

        // Device Compliance Section
        int total = compliance.Compliant + compliance.Noncompliant + compliance.Unknown;
        int compliantPct = total > 0 ? (int)Math.Round(100.0 * compliance.Compliant / total) : 0;
        int noncompliantPct = total > 0 ? 100 - compliantPct : 0;

        sb.Append("<div class=\"section\">");
        sb.Append("<div class=\"section-header\"><div class=\"section-icon blue\">🛡️</div><div class=\"section-title\">Device Compliance</div></div>");
        sb.Append($"<div class=\"section-summary\">{total} managed devices — {compliance.Compliant} compliant, {compliance.Noncompliant} noncompliant.</div>");
        sb.Append($"<div class=\"compliance-bar\"><div class=\"compliant\" style=\"width:{compliantPct}%\"></div><div class=\"noncompliant\" style=\"width:{noncompliantPct}%\"></div></div>");
        sb.Append("<div class=\"compliance-legend\">");
        sb.Append($"<div class=\"legend-item\"><div class=\"legend-dot green\"></div> Compliant ({compliantPct}%)</div>");
        sb.Append($"<div class=\"legend-item\"><div class=\"legend-dot red\"></div> Noncompliant ({noncompliantPct}%)</div>");
        sb.Append("</div>");

        // Noncompliant devices table
        sb.Append("<table><thead><tr><th>Device Name</th><th>OS</th><th>OS Version</th><th>User</th><th>Status</th><th>Last Sync (" + timeZone + ")</th></tr></thead><tbody>");
        foreach (var d in noncompliantDevices)
        {
            var syncTime = ConvertToAtlantic(d.LastSync);
            sb.Append($"<tr><td>{Esc(d.DeviceName)}</td><td>{Esc(d.Os)}</td><td class=\"mono\">{Esc(d.OsVersion)}</td>");
            sb.Append($"<td>{Esc(d.User)}</td><td><span class=\"badge badge-noncompliant\">Noncompliant</span></td>");
            sb.Append($"<td>{syncTime}</td></tr>");
        }
        sb.Append("</tbody></table></div>");

        // Vulnerabilities Section — portal-style summary cards
        sb.Append("<div class=\"section\">");
        sb.Append("<div class=\"section-header\"><div class=\"section-icon red\">🔓</div><div class=\"section-title\">Vulnerabilities</div></div>");
        sb.Append($"<div class=\"section-summary\">{vulnSummary.Total} unique vulnerabilities across {vulnSummary.AffectedDevices} devices.</div>");

        // Vulnerability summary cards (like Defender portal)
        sb.Append("<div class=\"ring-cards\" style=\"grid-template-columns: repeat(3, 1fr); margin-bottom: 20px;\">");
        sb.Append($"<div class=\"ring-card\"><div class=\"ring-stat-row\"><span style=\"color:var(--sfi-gray-500)\">Total Vulnerabilities</span><span style=\"font-weight:700;font-size:20px;color:var(--sfi-blue)\">{vulnSummary.Total}</span></div></div>");
        sb.Append($"<div class=\"ring-card\"><div class=\"ring-stat-row\"><span style=\"color:var(--sfi-gray-500)\">Exploitable</span><span style=\"font-weight:700;font-size:20px;color:var(--sfi-orange)\">{vulnSummary.Exploitable}</span></div></div>");
        sb.Append($"<div class=\"ring-card\"><div class=\"ring-stat-row\"><span style=\"color:var(--sfi-gray-500)\">Zero-Day</span><span style=\"font-weight:700;font-size:20px;color:var(--sfi-red)\">{vulnSummary.ZeroDay}</span></div></div>");
        sb.Append("</div>");
        sb.Append("<div class=\"ring-cards\" style=\"grid-template-columns: repeat(4, 1fr); margin-bottom: 20px;\">");
        sb.Append($"<div class=\"ring-card\"><div class=\"ring-stat-row\"><span style=\"color:var(--sfi-gray-500)\">Critical</span><span style=\"font-weight:700;color:var(--sfi-red)\">{vulnSummary.Critical}</span></div></div>");
        sb.Append($"<div class=\"ring-card\"><div class=\"ring-stat-row\"><span style=\"color:var(--sfi-gray-500)\">High</span><span style=\"font-weight:700;color:var(--sfi-orange)\">{vulnSummary.High}</span></div></div>");
        sb.Append($"<div class=\"ring-card\"><div class=\"ring-stat-row\"><span style=\"color:var(--sfi-gray-500)\">With Security Update</span><span style=\"font-weight:700;color:var(--sfi-green)\">{vulnSummary.WithUpdate}</span></div></div>");
        sb.Append($"<div class=\"ring-card\"><div class=\"ring-stat-row\"><span style=\"color:var(--sfi-gray-500)\">No Security Update</span><span style=\"font-weight:700;color:var(--sfi-red)\">{vulnSummary.WithoutUpdate}</span></div></div>");
        sb.Append("</div>");

        // Per-device vulnerability table
        sb.Append("<table><thead><tr><th>Device</th><th>Top CVEs</th><th>Max CVSS</th><th>Unique CVEs</th><th>Software Affected</th></tr></thead><tbody>");
        foreach (var v in vulnerabilities.OrderByDescending(x => x.MaxCvss).Take(50))
        {
            var severityClass = v.MaxCvss >= 9.0 ? "critical" : v.MaxCvss >= 7.0 ? "high" : "medium";
            var topCves = string.Join(", ", v.CveIds.Take(3));
            if (v.CveIds.Count > 3) topCves += $" (+{v.CveIds.Count - 3} more)";
            var software = string.Join(", ", v.Software.Take(3));

            sb.Append($"<tr><td>{Esc(v.DeviceName)}</td><td class=\"mono\">{Esc(topCves)}</td>");
            sb.Append($"<td><span class=\"badge badge-{severityClass}\"><strong>{v.MaxCvss:F1}</strong></span></td>");
            sb.Append($"<td>{v.CveIds.Count}</td><td>{Esc(software)}</td></tr>");
        }
        sb.Append("</tbody></table></div>");

        // Windows Update Section — use update status data
        sb.Append("<div class=\"section\">");
        sb.Append("<div class=\"section-header\"><div class=\"section-icon green\">🔄</div><div class=\"section-title\">Windows Update Status</div></div>");
        sb.Append("<div class=\"section-summary\">Update ring compliance across managed Windows devices.</div>");
        if (updateStatus.DeviceCount > 0)
        {
            // Show overall status card
            sb.Append("<div class=\"ring-cards\" style=\"margin-bottom: 16px;\">");
            sb.Append("<div class=\"ring-card\">");
            sb.Append("<div class=\"ring-card-title\">Overall Update Status</div>");
            sb.Append($"<div class=\"ring-stat-row\"><span style=\"color:var(--sfi-gray-500)\">Device Count</span><span style=\"font-weight:600\">{updateStatus.DeviceCount}</span></div>");
            sb.Append($"<div class=\"ring-stat-row\"><span style=\"color:var(--sfi-gray-500)\">Up to Date</span><span style=\"font-weight:600;color:var(--sfi-green)\">{updateStatus.CompliantCount}</span></div>");
            sb.Append($"<div class=\"ring-stat-row\"><span style=\"color:var(--sfi-gray-500)\">Not Up to Date</span><span style=\"font-weight:600;color:var(--sfi-orange)\">{updateStatus.NonCompliantCount}</span></div>");
            sb.Append($"<div class=\"ring-stat-row\"><span style=\"color:var(--sfi-gray-500)\">In Progress</span><span style=\"font-weight:600;color:var(--sfi-blue)\">{updateStatus.PendingCount}</span></div>");
            sb.Append($"<div class=\"ring-stat-row\"><span style=\"color:var(--sfi-gray-500)\">Not Ready</span><span style=\"font-weight:600;color:var(--sfi-red)\">{updateStatus.ErrorCount}</span></div>");
            sb.Append("</div>");
            sb.Append("</div>");
        }
        // Show ring configurations
        sb.Append("<div class=\"ring-cards\">");
        foreach (var ring in updateRings)
        {
            sb.Append("<div class=\"ring-card\">");
            sb.Append($"<div class=\"ring-card-title\">{Esc(ring.Name)}</div>");
            sb.Append($"<div class=\"ring-stat-row\"><span style=\"color:var(--sfi-gray-500)\">Deferral (Quality)</span><span style=\"font-weight:600\">{ring.QualityDeferral} days</span></div>");
            sb.Append($"<div class=\"ring-stat-row\"><span style=\"color:var(--sfi-gray-500)\">Deferral (Feature)</span><span style=\"font-weight:600\">{ring.FeatureDeferral} days</span></div>");
            sb.Append("</div>");
        }
        sb.Append("</div></div>");

        // Stale Devices Section
        sb.Append("<div class=\"section\">");
        sb.Append("<div class=\"section-header\"><div class=\"section-icon orange\">📱</div><div class=\"section-title\">Stale Devices</div></div>");
        sb.Append($"<div class=\"section-summary\">{staleDevices.Count} devices have not synced in over 30 days.</div>");
        sb.Append("<table><thead><tr><th>Device Name</th><th>User</th><th>Last Sync (" + timeZone + ")</th><th>Days Inactive</th><th>Compliance</th></tr></thead><tbody>");
        foreach (var d in staleDevices.OrderByDescending(x => x.DaysInactive))
        {
            var color = d.DaysInactive > 180 ? "var(--sfi-red)" : "var(--sfi-orange)";
            var syncTime = ConvertToAtlantic(d.LastSync);
            sb.Append($"<tr><td>{Esc(d.DeviceName)}</td><td>{Esc(d.User)}</td><td>{syncTime}</td>");
            sb.Append($"<td style=\"font-weight:700;color:{color}\">{d.DaysInactive}</td>");
            sb.Append($"<td><span class=\"badge badge-noncompliant\">Noncompliant</span></td></tr>");
        }
        sb.Append("</tbody></table></div>");

        // Footer
        sb.Append(GetFooter("Devices & Vulnerabilities Report", now, timeZone));
        sb.Append("</body></html>");

        _logger.LogInformation("Devices & Vulnerabilities Report generated successfully");
        return sb.ToString();
    }

